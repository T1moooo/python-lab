# ------------------------------------------------------------
# 第一部分：导入模块
# ------------------------------------------------------------

# os 是 Python 的标准库，提供了和操作系统交互的功能
# 我们用它来读取环境变量（os.getenv）
import os

# dotenv 是一个第三方包，用来加载 .env 文件中的环境变量
# .env 文件是一个纯文本文件，每行一个 KEY=VALUE
# load_dotenv() 会读取 .env 文件，把里面的变量设置到环境变量中
# 这样 os.getenv("OPENROUTER_API_KEY") 就能读到你填的 key
from dotenv import load_dotenv

# from ... import ... 是 Python 的导入语法
# 意思是：从 openai 这个包里，导入 OpenAI 这个类
#
# 什么是"包"（package）？
#   包就是别人写好的代码集合，我们可以通过 pip / uv 安装后直接使用
#   openai 就是 OpenAI 官方提供的 Python SDK（软件开发工具包）
#
# 什么是"类"（class）？
#   类可以理解为一个"模板"或"蓝图"
#   OpenAI 这个类就是用来创建"OpenAI 客户端"的模板
#   我们后面会用 client = OpenAI(...) 来创建一个具体的客户端对象
from openai import OpenAI


# ------------------------------------------------------------
# 第二部分：创建 OpenAI 客户端
# ------------------------------------------------------------

# client = OpenAI(...) 是在创建一个 OpenAI 客户端"实例"
#
# 什么是"实例"（instance）？
#   类是模板，实例是根据模板造出来的具体对象
#   比如"汽车图纸"是类，"我家门口那辆红色轿车"是实例
#
# load_dotenv() 加载 .env 文件中的变量到环境变量
# 这样下面的 os.getenv() 才能读到值
load_dotenv()

# OpenAI() 括号里传的是"参数"（arguments）：
#
# 参数1: base_url
#   这是 API 的基础地址
#   我们用的是 OpenRouter（一个统一的 AI 模型网关）
#   OpenRouter 兼容 OpenAI 的 API 格式，所以可以用 openai 这个 SDK
#   如果直接用 OpenAI 的服务，base_url 会是 "https://api.openai.com/v1"
#
# 参数2: api_key
#   这是你的身份凭证，相当于密码
#   API 服务器通过这个 key 知道"是谁在调用接口"
#   没有 key 或 key 错误，服务器会拒绝你的请求
#
#   os.getenv("OPENROUTER_API_KEY") 从环境变量中读取 key
#   这样 key 就不需要写死在代码里了
#   环境变量的值来自 .env 文件（由上面的 load_dotenv() 加载）
client = OpenAI(
    base_url="https://openrouter.ai/api/v1",
    api_key=os.getenv("OPENROUTER_API_KEY"),
)


# ------------------------------------------------------------
# 第三部分：定义模型名称
# ------------------------------------------------------------

# 这是一个普通的变量赋值
# = 右边是一个字符串，用双引号包裹
#
# MODEL 是我们约定的常量名（全大写是 Python 的命名惯例，表示"这个值不应该被修改"）
# 这个字符串告诉 OpenRouter 我们想用哪个 AI 模型
#
# "openai/gpt-oss-120b:free" 是 OpenRouter 上的一个免费模型
# 格式是 "提供商/模型名"
MODEL = "openai/gpt-oss-120b:free"


# ------------------------------------------------------------
# 第四部分：初始化对话历史
# ------------------------------------------------------------

# history 是一个"列表"（list），用方括号 [] 表示
# 列表是 Python 最常用的数据结构之一，可以存放多个值
#
# 列表里的每个元素是一个"字典"（dict），用花括号 {} 表示
# 字典由"键-值对"（key-value pair）组成
# 比如 {"role": "system", "content": "..."} 里：
#   "role" 是键，"system" 是值
#   "content" 是键，"You are a helpful Python tutor." 是值
#
# 为什么需要 history？
#   AI 模型本身没有记忆，每次请求都是独立的
#   要让 AI 记住之前的对话，我们必须把"完整对话历史"一起发给它
#   所以我们用一个列表来保存所有消息
#
# 第一条消息的 role 是 "system"，这是"系统提示"（system prompt）
# 系统提示用来设定 AI 的身份和行为规则
# 用户看不到这条消息，但 AI 会按照这个指令来行事
history = [
    {"role": "system", "content": "You are a helpful Python tutor."}
]


# ------------------------------------------------------------
# 第五部分：欢迎信息
# ------------------------------------------------------------

# print() 是 Python 的内置函数，用来在终端打印文字
# \n 是"换行符"，会在文字后面空一行
print("CLI Chatbot 已启动，输入 quit 退出\n")


# ------------------------------------------------------------
# 第六部分：主循环
# ------------------------------------------------------------

# while True 创建一个"无限循环"
# 只要条件是 True，循环体里的代码就会反复执行
# 我们靠内部的 break 语句来退出循环
while True:

    # --------------------------------------------------------
    # 6.1 读取用户输入
    # --------------------------------------------------------

    # input() 是 Python 的内置函数
    # 它会在终端显示括号里的提示文字，然后等待用户输入
    # 用户按下回车后，输入的内容会作为字符串返回
    # 我们把这个字符串存到 user_input 变量里
    user_input = input("You: ")

    # --------------------------------------------------------
    # 6.2 检查退出条件
    # --------------------------------------------------------

    # .strip() 是字符串方法，去掉首尾的空格和换行
    # .lower() 是字符串方法，把所有字母变成小写
    # 这样不管用户输入 "quit"、"QUIT"、" quit "，都能正确识别
    #
    # == 是"比较运算符"，判断两边是否相等
    # 返回 True 或 False
    #
    # if 语句：如果条件为 True，就执行缩进的代码块
    #
    # break 语句：立刻跳出当前的 while 循环
    if user_input.strip().lower() == "quit":
        print("再见！")
        break

    # --------------------------------------------------------
    # 6.3 把用户消息加入历史
    # --------------------------------------------------------

    # .append() 是列表的方法，往列表末尾添加一个元素
    # 这里我们把用户的消息构造成 {"role": "user", "content": "..."} 的格式
    # 然后追加到 history 列表的末尾
    #
    # role 的值是 "user"，表示这是用户说的话
    history.append({"role": "user", "content": user_input})

    # --------------------------------------------------------
    # 6.4 调用 AI API
    # --------------------------------------------------------

    # client.chat.completions.create() 是调用 AI 的核心方法
    #
    # 理解这个调用链：
    #   client              → 我们创建的 OpenAI 客户端对象
    #   .chat               → 访问"聊天"功能模块
    #   .completions        → 访问"补全"功能模块
    #   .create()           → 调用"创建补全"方法
    #
    # 你可以类比为：打开手机 → 打开微信 → 打开对话 → 发送消息
    #
    # 参数 model=MODEL：
    #   指定使用哪个 AI 模型
    #   = 左边的 model 是参数名，= 右边的 MODEL 是我们定义的变量
    #
    # 参数 messages=history：
    #   把完整的对话历史发给 AI
    #   AI 会根据历史上下文来生成回复
    #   history 里包含 system 消息 + 所有之前的 user 和 assistant 消息
    #
    # 这个调用会"阻塞"（block）——程序会停在这里等待服务器返回结果
    # 可能需要几秒到十几秒，取决于网络和模型速度
    response = client.chat.completions.create(
        model=MODEL,
        messages=history,
    )

    # --------------------------------------------------------
    # 6.5 提取 AI 回复
    # --------------------------------------------------------

    # response 是服务器返回的"响应对象"
    # 它包含很多信息，我们只需要 AI 生成的文字
    #
    # response.choices       → 所有候选回答（通常只有一个）
    # response.choices[0]    → 第一个候选回答（[0] 是列表索引，取第一个元素）
    # .message               → 取出消息对象
    # .content               → 取出消息的文本内容
    #
    # 这一串用英文点号 . 连接的写法叫"链式调用"
    # 每个 . 都是在访问前一个对象的属性或方法
    reply = response.choices[0].message.content

    # --------------------------------------------------------
    # 6.6 打印 AI 回复
    # --------------------------------------------------------

    # f"AI: {reply}" 是 f-string 格式化字符串
    # f-string 以 f 开头，花括号 {} 里的变量会被替换成它的值
    # 比如 reply 是 "Hello"，那 f"AI: {reply}" 就变成 "AI: Hello"
    #
    # \n 在末尾加一个空行，让每次对话之间有间隔，更好看
    print(f"AI: {reply}\n")

    # --------------------------------------------------------
    # 6.7 把 AI 回复加入历史
    # --------------------------------------------------------

    # 和用户消息一样，AI 的回复也要加入 history
    # 这样下次请求时，AI 就知道自己之前说过什么
    #
    # role 的值是 "assistant"，表示这是 AI 说的话
    # "assistant" 是 OpenAI API 的约定：AI 的角色叫 assistant
    history.append({"role": "assistant", "content": reply})
